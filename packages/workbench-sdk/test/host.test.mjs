import assert from 'node:assert/strict';
import {resolve} from 'node:path';
import {pathToFileURL} from 'node:url';
const required=['WB21_HOST_URL','WB21_STORAGE_STATE','WB21_INSTALL_ID','WB21_DATA_EXPECT','WB21_FILE_NAME','WB21_PLAYWRIGHT_MODULE'];
for(const name of required)if(!process.env[name])throw Error('Set '+name+' for the isolated real-host exercise');
const url=new URL(process.env.WB21_HOST_URL);
assert.ok(['127.0.0.1','localhost','[::1]'].includes(url.hostname),'Use an isolated loopback test host');
const {chromium}=await import(pathToFileURL(resolve(process.env.WB21_PLAYWRIGHT_MODULE)).href);
const browser=await chromium.launch({headless:true});
try {
 const context=await browser.newContext({storageState:resolve(process.env.WB21_STORAGE_STATE)});
 const catalog=await context.request.get(new URL('/api/v1/workbench/catalog',url).href);
 assert.equal(catalog.status(),200);
 const item=(await catalog.json()).data.items.find(item=>item.binding?.installId===process.env.WB21_INSTALL_ID&&item.declaration.id==='reports');
 assert.ok(item,'Import the independent consumer ZIP into the isolated host first');
 const page=await context.newPage();
 await page.goto(new URL('/apps/'+encodeURIComponent(item.applicationKey)+'/overview',url).href);
 const frame=page.frameLocator('iframe');
 await frame.locator('#status').filter({hasText:'Ready'}).waitFor();
 await frame.locator('#files').click();
 await frame.locator('#route').filter({hasText:'files'}).waitFor();
 await page.reload();
 await frame.locator('#route').filter({hasText:'files'}).waitFor();
 await frame.locator('#overview').click();
 await page.goBack();
 await frame.locator('#route').filter({hasText:'files'}).waitFor();
 await frame.locator('#query').click();
 const approval=page.getByRole('dialog');
 await approval.getByRole('button',{name:/^(允许|Allow)$/}).click();
 await frame.locator('#result').filter({hasText:process.env.WB21_DATA_EXPECT}).waitFor();
 const data=JSON.parse(await frame.locator('#result').innerText());
 assert.notEqual(data.simulation,true,'A real host must not use preview data');
 await frame.locator('#pick').click();
 await page.getByRole('dialog').getByRole('combobox').selectOption({label:process.env.WB21_FILE_NAME});
 await page.getByRole('dialog').getByRole('button',{name:/^(允许|Allow)$/}).click();
 await frame.locator('#save:not([disabled])').waitFor();
 const selected=JSON.parse(await frame.locator('#result').innerText());
 assert.notEqual(selected.fileId,'preview-file');
 const download=page.waitForEvent('download');
 await frame.locator('#save').click();
 await page.getByRole('dialog').getByRole('button',{name:/^(允许|Allow)$/}).click();
 await download;
 await frame.locator('#result').filter({hasText:'"saved": true'}).waitFor();
 console.log('Real host example navigation/data/file path passed. Revocation and cross-user checks remain separate.');
} finally {await browser.close();}
