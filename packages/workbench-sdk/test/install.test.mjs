import assert from 'node:assert/strict';
import {spawnSync} from 'node:child_process';
import {mkdtempSync,writeFileSync,readFileSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join,resolve} from 'node:path';
const root=resolve('.');
const consumer=mkdtempSync(join(tmpdir(),'wb07-consumer-'));
const run=(args,cwd=root)=>{const r=spawnSync('npm',args,{cwd,encoding:'utf8'}); assert.equal(r.status,0,r.stdout+r.stderr); return r.stdout;};
const pack=JSON.parse(run(['pack','--json','--pack-destination',consumer]))[0];
writeFileSync(join(consumer,'package.json'),JSON.stringify({private:true,type:'module'}));
run(['install','--ignore-scripts','--offline',join(consumer,pack.filename)],consumer);
writeFileSync(join(consumer,'probe.mjs'),"import {connect,SDK_VERSION} from '@hugagent/workbench-sdk'; if(typeof connect!=='function'||SDK_VERSION!=='1.0.0') throw Error('bad exports');");
const r=spawnSync(process.execPath,['probe.mjs'],{cwd:consumer,encoding:'utf8'});
assert.equal(r.status,0,r.stderr);
writeFileSync(join(consumer,'probe.ts'),"import {connect,type HostInfo,type FileReference} from '@hugagent/workbench-sdk'; async function probe(){const c=await connect(); const info=await c.request<HostInfo>('host.info'); const file:FileReference|null=await c.pickFile({accept:'.txt'}); await c.query('files',{limit:1}); if(file)await c.saveFile({fileId:file.fileId}); await c.composeChat({text:'draft'}); await c.openApplication({applicationKey:'builtin:chat'}); c.dispose(); return info.context.installId;} void probe;");
const types=spawnSync(process.execPath,[resolve('node_modules/typescript/bin/tsc'),join(consumer,'probe.ts'),'--noEmit','--moduleResolution','bundler','--module','ESNext','--target','ES2022','--lib','ES2022,DOM'],{cwd:consumer,encoding:'utf8'});
assert.equal(types.status,0,types.stdout+types.stderr);
const manifest=JSON.parse(readFileSync('package.json'));
assert.equal(manifest.private,true); assert.equal(manifest.license,'UNLICENSED');
assert.ok(!manifest.dependencies?.react);
console.log('independent SDK consumer passed');
