import assert from 'node:assert/strict';
import {mkdtemp, writeFile, readFile, mkdir} from 'node:fs/promises';
import {execFileSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';
import {join} from 'node:path';
const root = fileURLToPath(new URL('../../../', import.meta.url));
const sandbox = await mkdtemp(join(root, '.scratch/workbench-02/consumer-'));
const output = execFileSync('npm', ['pack', '--json', '--pack-destination', sandbox], {
  cwd: root + 'packages/workbench-protocol', encoding: 'utf8',
});
const packed = JSON.parse(output)[0];
assert.ok(packed.files.some(f => f.path === 'dist/index.d.ts'));
assert.ok(packed.files.some(f => f.path === 'schemas/application.schema.json'));
assert.ok(packed.files.some(f => f.path === 'fixtures/applications.json'));
assert.ok(packed.files.every(f => !f.path.includes('node_modules') && !f.path.startsWith('src/')));
await writeFile(join(sandbox, 'package.json'), JSON.stringify({private: true, type: 'module'}));
execFileSync('npm', ['install', '--ignore-scripts', '--offline', '--no-audit', '--no-fund', join(sandbox, packed.filename)], {cwd: sandbox, stdio: 'inherit'});
const installed = JSON.parse(await readFile(join(sandbox, 'node_modules/@hugagent/workbench-protocol/package.json')));
assert.equal(installed.private, true);
assert.equal(installed.license, 'UNLICENSED');
assert.equal(installed.dependencies, undefined, 'validator runtime must be bundled');
const consumer = `import assert from 'node:assert/strict';
import {validateApplication, PROTOCOL_VERSION} from '@hugagent/workbench-protocol';
import {DOCUMENT_VIEWS} from '@hugagent/workbench-protocol/legacy';
assert.equal(PROTOCOL_VERSION, '1.0.0');
assert.equal(DOCUMENT_VIEWS.includes('list'), true);
assert.deepEqual(validateApplication({schemaVersion:'1.0.0',id:'reports',title:'Reports',target:{kind:'command',commandId:'show'}},{commandIds:['show']}), []);
console.log('independent installed runtime passed');
`;
await writeFile(join(sandbox, 'consumer.mjs'), consumer);
execFileSync(process.execPath, ['consumer.mjs'], {cwd: sandbox, stdio: 'inherit'});
await writeFile(join(sandbox, 'consumer.ts'), `import type {ApplicationDeclaration, RegisteredApplication} from '@hugagent/workbench-protocol';
import type {ModuleContribution} from '@hugagent/workbench-protocol/legacy';
const app: ApplicationDeclaration = {schemaVersion:'1.0.0',id:'reports',title:'Reports',target:{kind:'plugin',moduleId:'main'}};
const module: ModuleContribution = {id:'main',entry:'web/main.html',surface:'workspace',title:'Reports',grants:[]};
const registered: RegisteredApplication = {id:'reports',target:{kind:'builtin',componentId:'page'}};
console.log(app, module, registered);
`);
execFileSync(process.execPath, [root + 'packages/workbench-protocol/node_modules/typescript/bin/tsc', '--strict', '--noEmit', '--module', 'NodeNext', '--target', 'ES2022', 'consumer.ts'], {cwd: sandbox, stdio: 'inherit'});
await writeFile(join(root, '.scratch/workbench-02/install-result.json'), JSON.stringify({sandbox, filename: packed.filename, shasum: packed.shasum, size: packed.size}, null, 2));
console.log('independent tarball install and TypeScript exports passed');
