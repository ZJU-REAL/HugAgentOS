import assert from 'node:assert/strict';
import {InstancePool, instanceKey, type InstanceIdentity} from '../src/workbench/lifecycle/instancePool';
const identity=(key:string):InstanceIdentity=>({userId:'alice',applicationKey:key,installId:'install',packageRevision:'r1',executionScope:'cloud',origin:'test-origin',workspace:'main'});
let allow=false, loads=0, disposed=0;
const pool=new InstancePool<string>({confirmDiscard:()=>allow,dispose:()=>{disposed++;}});
const load=async()=>{loads++;return 'page';};
await pool.activate(identity('a'),load);
await pool.activate(identity('a'),load);
assert.equal(loads,1);
pool.markReady(instanceKey(identity('a')));
pool.setDirty(instanceKey(identity('a')),true);
assert.equal(await pool.activate(identity('b'),load),false);
assert.equal(loads,1);
allow=true;
assert.equal(await pool.activate(identity('b'),load),true);
assert.equal(disposed,1);
await pool.activate(identity('c'),load);
await pool.activate(identity('d'),load);
assert.equal(pool.snapshot().length,3);
await pool.activate(identity('e'),load);
assert.deepEqual(pool.snapshot().map(x=>x.identity.applicationKey),['c','d','e']);
assert.equal(disposed,2);
const e=instanceKey(identity('e'));
pool.setDirty(e,true);
pool.revoke(x=>x.identity.applicationKey==='e');
assert.equal(pool.snapshot().some(x=>x.id===e),false);
assert.equal(disposed,3);
let complete!:(value:string)=>void;
const late=pool.activate(identity('late'),()=>new Promise(resolve=>{complete=resolve;}));
await new Promise(resolve=>setTimeout(resolve,0));
pool.clear();
complete('stale');
assert.equal(await late,true);
assert.equal(pool.snapshot().length,0);
const crash=new InstancePool<string>({confirmDiscard:()=>false,dispose:()=>{}});
await crash.activate(identity('broken'),async()=>{throw new Error('unavailable');});
await new Promise(resolve=>setTimeout(resolve,0));
assert.equal(crash.snapshot()[0].status,'failed');
await crash.retryCurrent(load);
assert.equal(crash.snapshot()[0].status,'loading');
console.log('WB10 instance budget, duplicate open, dirty cancellation, revoke, stale load and retry passed');

// A stalled instance does not delay opening another application.
let release!:(value:string)=>void;
const independent=new InstancePool<string>({confirmDiscard:()=>false,dispose:()=>{}});
await independent.activate(identity('stalled'),()=>new Promise(resolve=>{release=resolve;}));
await independent.activate(identity('responsive'),load);
assert.equal(independent.currentId,instanceKey(identity('responsive')));
independent.clear();release('old');
await new Promise(resolve=>setTimeout(resolve,0));
assert.equal(independent.snapshot().length,0);
const queued=new InstancePool<string>({confirmDiscard:()=>false,dispose:()=>{}});
const pending=queued.activate(identity('never'),load);
queued.clear();
assert.equal(await pending,false);
assert.equal(queued.snapshot().length,0);

const documents=new InstancePool<string>({confirmDiscard:()=>true,dispose:()=>{}});
await documents.activate(identity('a'),async()=>'main',true,'main');
const stableId=documents.snapshot()[0].instanceId;
await documents.replaceCurrent(async()=>'details','details');
await new Promise(resolve=>setTimeout(resolve,0));
assert.equal(documents.snapshot()[0].value,'details');
assert.equal(documents.snapshot()[0].instanceId,stableId);
await documents.activate(identity('b'),load);
await documents.activate(identity('a'),async()=>'main',true,'main');
await new Promise(resolve=>setTimeout(resolve,0));
assert.equal(documents.snapshot().find(x=>x.instanceId===stableId)?.value,'main');
