import assert from 'node:assert/strict';
import { builtinNavigation } from '../src/applicationNavigation';
const config={ sidebar:['sites','sites','ability_center','my_space','unknown'], menu:['settings','projects','lab','projects','app_center'] };
const nav=builtinNavigation(config, {labEnabled:false,localOnly:true});
assert.deepEqual(nav.primary, ['automation','ability_center']);
assert.deepEqual(nav.sidebar, ['ability_center']);
assert.deepEqual(nav.menu, ['projects','app_center']);
assert.deepEqual(nav.more, ['projects','app_center']);
const full=builtinNavigation(config, {labEnabled:true,localOnly:false});
assert.deepEqual(full.primary, ['my_space','automation','ability_center']);
assert.deepEqual(full.sidebar, ['sites','ability_center','my_space']);
assert.deepEqual(full.menu, ['projects','lab','app_center']);
assert.deepEqual(full.more, ['sites','projects','lab','app_center']);
console.log('workbench navigation: same availability, order and deduplication for both layouts');
