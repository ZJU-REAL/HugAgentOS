"""Host-owned publication of local skill views and installation revisions."""
from __future__ import annotations
from dataclasses import dataclass
from typing import Any, Protocol

class LocalPublication(Protocol):
    def management_lock_path(self): ...
    def provision_plugin_assets(self, slug): ...
    def migrate_local_plugins(self): ...
    def migrate_local_skills(self): ...
    async def ensure_native_servers(self, configs): ...
    def publish_local_plugin(self, definition, *, owner_user_id): ...
    def remove_local_plugin(self, slug): ...
    def skill_backend(self, *, priority=150, local=False): ...
    def merge_skill_infos(self, groups, *, backend_hash): ...
    def view_generation(self): ...
    def skill_root(self): ...
    def merge_visible_agents(self, user_id, rows): ...
    def account_agent_definition(self, agent_id): ...
    def publish_local_agent(self, definition): ...
    def remove_local_agent(self, agent_id): ...
    def rebuild_device_view(self) -> Any: ...
    def rebuild_user_view(self, user_id: str) -> Any: ...
    def rebuild_views(self, user_id: str | None) -> Any: ...
    def remove_local_skill(self, skill_id: str) -> bool: ...
    def prune_local(self, owners: dict) -> int: ...
    def publish_local_skill(self, *args: Any, **kwargs: Any) -> Any: ...
    def device_view_dir(self) -> Any: ...
    def user_view_dir(self, user_id: str | None) -> Any: ...
    def stamp_installation(self, db: Any, install_id: str, stamp: Any) -> None: ...
    def claim_revision(self, db: Any, install_id: str, expected_revision: str) -> int: ...


def register_local_publication(provider: LocalPublication) -> None:
    pass
    registration_state().provider = provider

def local_publication() -> LocalPublication:
    if registration_state().provider is None:
        raise RuntimeError("Host must register local publication before changing local capabilities")
    return registration_state().provider


def provision_plugin_assets(slug):
    return local_publication().provision_plugin_assets(slug)


def migrate_local_plugins():
    return local_publication().migrate_local_plugins()


def migrate_local_skills():
    return local_publication().migrate_local_skills()


async def ensure_native_servers(configs):
    return await local_publication().ensure_native_servers(configs)


@dataclass
class RegistrationState:
    provider: LocalPublication | None = None


_REGISTRATIONS = RegistrationState()


def registration_state() -> RegistrationState:
    return _REGISTRATIONS
